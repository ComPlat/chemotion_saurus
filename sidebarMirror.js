// Builds the sidebar for a non-default docs plugin instance.
//
// Docusaurus cannot share one sidebar across plugin instances -- instances are
// sandboxed, so each can only render its own docs, and the maintainers have
// said no first-class feature is planned for this. The workaround every
// unversioned instance here uses is to mirror the *other* top-level sections as
// plain links, with its own content expanded in place, so the sidebar still
// reads as one continuous list while navigating between instances.
//
// Order, labels and hrefs come from mainSiteSections.js, the single source of
// truth shared with the default instance's sidebarItemsGenerator.js.
const logger = require("@docusaurus/logger").default;
const mainSiteSections = require("./mainSiteSections.js");

/**
 * @param {string} selfLabel  this instance's entry in mainSiteSections.js
 * @param {object[]} [selfItems]  what to expand in place; defaults to the whole
 *   instance, autogenerated. Pass an explicit list for a single-page instance,
 *   where there is no folder to walk.
 */
module.exports = function sidebarMirror(selfLabel, selfItems) {
  const selfIndex = mainSiteSections.findIndex((s) => s.label === selfLabel);
  if (selfIndex === -1) {
    // Fallback: the label was renamed in mainSiteSections.js but not here.
    // Render this instance's own content rather than an empty sidebar, but warn
    // -- otherwise the cross-section links would silently disappear.
    logger.warn(
      `sidebarMirror: "${selfLabel}" is not in mainSiteSections.js, so the other sections cannot be mirrored into this instance's sidebar. Rendering its own content only.`,
    );
    return { sidebar: selfItems ?? [{ type: "autogenerated", dirName: "." }] };
  }
  return {
    sidebar: [
      ...mainSiteSections.slice(0, selfIndex).map((s) => ({ type: "link", ...s })),
      ...(selfItems ?? [{ type: "autogenerated", dirName: "." }]),
      ...mainSiteSections.slice(selfIndex + 1).map((s) => ({ type: "link", ...s })),
    ],
  };
};
