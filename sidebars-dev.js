// "Development" (of the Chemotion ELN) is its own docs plugin instance -- see
// docusaurus.config.js -- and is deliberately unversioned: it documents the ELN's
// development process (git workflow, CI, testing, linting), which is tied to the
// ELN repository rather than to a release of these docs.
//
// Same shape as sidebars-repo.js / sidebars-meta.js: mirror every *other*
// top-level section as a plain link, with this instance's own content expanded
// in place. Order, labels and hrefs come from mainSiteSections.js.
const mainSiteSections = require("./mainSiteSections.js");

const selfIndex = mainSiteSections.findIndex((s) => s.label === "Development");
const before = mainSiteSections.slice(0, selfIndex);
const after = mainSiteSections.slice(selfIndex + 1);

module.exports = {
  sidebar: [
    ...before.map((s) => ({ type: "link", ...s })),
    {
      type: "autogenerated",
      dirName: ".",
    },
    ...after.map((s) => ({ type: "link", ...s })),
  ],
};
